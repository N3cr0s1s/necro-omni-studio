/**
 * The theme a fresh installation gets: the one the application was designed in.
 *
 * Named rather than "the first entry", because the order of the array is a matter of how the picker
 * reads and the default is a decision.
 */
export const DEFAULT_THEME_ID = 'studio';

/** The theme with that id, or the default. A stored id from a build that had more themes is not an error. */
export function themeById(id: string | undefined): Theme {
  return (
    THEMES.find((theme) => theme.id === id) ??
    // Non-null by construction: the default id is one of the entries above, and the stylesheet test
    // would fail before this could return `undefined`.
    (THEMES.find((theme) => theme.id === DEFAULT_THEME_ID) as Theme)
  );
}

/** Whether an id names a theme this build has. Used where a stored value has to be validated. */
export function isThemeId(id: unknown): id is string {
  return typeof id === 'string' && THEMES.some((theme) => theme.id === id);
}
