/**
 * The themes this application ships.
 *
 * Issue #21's remaining half: "lehet majd több theme is". Every palette below is shadcn's own — five
 * from its colour registry, and the one the application was built in, read back out of the stylesheet
 * `npx shadcn init` wrote. **Nothing here was chosen by eye.** That is the point: the request was for
 * shadcn's theming, and a palette invented to look shadcn-ish would be the one thing that could not be
 * called that.
 *
 * `source` on each theme records where its numbers came from, so the next person to wonder has an
 * answer that is not "trust me".
 *
 * ## Adding one
 *
 * Append an entry. There is nothing else: the picker is built from this array, `themeCss` emits the
 * stylesheet from it, and `themes.test.ts` measures whatever it finds — so a theme added here is
 * offered, applied and contrast-checked without another line being written anywhere. That is what
 * "minden része a rendszernek bővíthető legyen" asks for, spelled as data.
 *
 * A theme that misses a role does not compile, and one whose text cannot be read does not pass. Both
 * are deliberate: the failure modes of a palette switch are invisible by nature, so they are moved to
 * where they are loud.
 *
 * ## Generated, and regenerable
 *
 * The bodies below were written by a script from the registry JSON rather than transcribed. A
 * transcription error in a colour is not something review catches — every value looks like every
 * other value — so the numbers arrive by copy and stay verified by the stylesheet test, which rebuilds
 * `globals.css` from this array and compares it to the file on disk.
 */
